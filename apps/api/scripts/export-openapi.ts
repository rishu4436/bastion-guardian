/**
 * Writes the OpenAPI document and a Markdown endpoint reference generated from the live route schemas:
 *   docs/api/openapi.json, docs/api/HTTP-REFERENCE.md
 * `--check` fails when the committed files are out of date (used in CI).
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadEnv } from "@bastion-guardian/config";
import { buildApp } from "../src/app.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const out = join(root, "docs/api");
const app = await buildApp({ env: loadEnv({ NODE_ENV: "test" }) });
await app.ready();
const spec = app.swagger() as {
  info: { title: string; version: string; description?: string };
  paths: Record<
    string,
    Record<
      string,
      {
        summary?: string;
        tags?: string[];
        description?: string;
        parameters?: { name: string; in: string; required?: boolean }[];
        requestBody?: unknown;
        security?: unknown;
      }
    >
  >;
};
await app.close();

const json = JSON.stringify(spec, null, 2) + "\n";
const byTag = new Map<string, string[]>();
for (const [path, ops] of Object.entries(spec.paths).sort(([a], [b]) => a.localeCompare(b)))
  for (const [method, op] of Object.entries(ops)) {
    const tag = op.tags?.[0] ?? "other";
    const params = (op.parameters ?? [])
      .map((p) => `\`${p.name}\`${p.in === "path" ? " (path)" : p.required ? " (required)" : ""}`)
      .join(", ");
    const auth =
      path.startsWith("/v1/me") || ["/v1/auth/csrf", "/v1/auth/logout", "/v1/auth/session"].includes(path)
        ? "session"
        : path.startsWith("/v1/admin") || path.startsWith("/v1/incidents")
          ? "session + role"
          : path === "/v1/solver/quotes"
            ? "EIP-712 solver signature"
            : "public";
    const row = `| \`${method.toUpperCase()}\` | \`${path}\` | ${op.summary ?? ""} | ${params || "-"} | ${op.requestBody ? "JSON" : "-"} | ${auth} |`;
    (byTag.get(tag) ?? byTag.set(tag, []).get(tag)!).push(row);
  }
let md = `# ${spec.info.title} — HTTP reference (v${spec.info.version})\n\n`;
md +=
  "_Generated by `pnpm --filter @bastion-guardian/api openapi` from the route schemas. Do not edit by hand._\n\n";
md += `${spec.info.description ?? ""}\n\n`;
md +=
  "Conventions: amounts, health factors (1e18 WAD) and block numbers are decimal integer strings. Errors are `{ error: CODE, message }`. " +
  "State-changing calls with a session need `X-CSRF-Token` (mint with `POST /v1/auth/csrf`, JSON body). Rate limits: 120 requests/min per client " +
  "by default (Redis-shared across instances), stricter on auth, channel and test-notification routes. Machine-readable spec: [`openapi.json`](./openapi.json); " +
  "interactive docs at `/docs` on any API instance.\n\n";
for (const [tag, rows] of [...byTag].sort(([a], [b]) => a.localeCompare(b))) {
  md += `## ${tag}\n\n| Method | Path | Summary | Parameters | Body | Auth |\n| --- | --- | --- | --- | --- | --- |\n${rows.join("\n")}\n\n`;
}
const files: [string, string][] = [
  [join(out, "openapi.json"), json],
  [join(out, "HTTP-REFERENCE.md"), md],
];
if (process.argv.includes("--check")) {
  const stale = files.filter(([f, c]) => !existsSync(f) || readFileSync(f, "utf8") !== c).map(([f]) => f);
  if (stale.length) {
    console.error(`Out of date: ${stale.join(", ")}. Run: pnpm --filter @bastion-guardian/api openapi`);
    process.exit(1);
  }
  console.log("API reference is up to date");
} else {
  mkdirSync(out, { recursive: true });
  for (const [f, c] of files) writeFileSync(f, c);
  console.log(`wrote ${files.map(([f]) => f).join(", ")}`);
}
